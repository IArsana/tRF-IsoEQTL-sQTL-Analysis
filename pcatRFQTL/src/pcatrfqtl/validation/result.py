from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import StrEnum
from typing import Any


class ValidationStatus(StrEnum):
    """
    Possible outcomes of a validation check.
    """

    PASS = "PASS"
    WARNING = "WARNING"
    FAIL = "FAIL"


class ValidationSeverity(StrEnum):
    """
    Severity level associated with a validation result.
    """

    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"


@dataclass
class ValidationCheck:
    """
    Represent the result of a single validation rule.
    """

    name: str
    status: ValidationStatus
    severity: ValidationSeverity
    message: str
    details: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the validation check to a dictionary.
        """

        return asdict(self)


@dataclass
class ValidationReport:
    """
    Represent the complete validation report for one dataset.

    The report contains validation checks, aggregate statistics,
    errors, and warnings.
    """

    dataset_id: str
    status: ValidationStatus = ValidationStatus.PASS
    checks: list[ValidationCheck] = field(default_factory=list)
    statistics: dict[str, Any] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def add_check(
        self,
        check: ValidationCheck,
    ) -> None:
        """
        Add a validation check to the report.
        """

        self.checks.append(check)

        if check.status == ValidationStatus.FAIL:
            self.status = ValidationStatus.FAIL
            self.errors.append(check.message)

        elif (
            check.status == ValidationStatus.WARNING
            and self.status != ValidationStatus.FAIL
        ):
            self.status = ValidationStatus.WARNING
            self.warnings.append(check.message)

    def add_statistics(
        self,
        statistics: dict[str, Any],
    ) -> None:
        """
        Add aggregate dataset statistics to the report.

        Existing statistics with the same keys are overwritten.
        """

        self.statistics.update(statistics)

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the validation report to a serializable dictionary.
        """

        return {
            "dataset_id": self.dataset_id,
            "status": self.status.value,
            "checks": [
                check.to_dict()
                for check in self.checks
            ],
            "statistics": self.statistics,
            "errors": self.errors,
            "warnings": self.warnings,
        }