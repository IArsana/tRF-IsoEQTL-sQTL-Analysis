def build_lead_synthesis(
    locus_evidence: pd.DataFrame,
    variant_recurrence: pd.DataFrame,
) -> pd.DataFrame:
    """Create one cross-study synthesis record per candidate lead."""

    records: list[
        dict[str, Any]
    ] = []

    for lead_rsid, group in locus_evidence.groupby(
        "lead_rsid",
        sort=True,
    ):

        minimum_p_values = pd.to_numeric(
            group[
                "minimum_p_value"
            ],
            errors="coerce",
        ).dropna()

        lead_p_values = pd.to_numeric(
            group[
                "lead_p_value"
            ],
            errors="coerce",
        ).dropna()

        top_distance_values = pd.to_numeric(
            group[
                "top_variant_absolute_distance_to_lead"
            ],
            errors="coerce",
        ).dropna()

        top_row = None

        if not minimum_p_values.empty:

            top_index = pd.to_numeric(
                group[
                    "minimum_p_value"
                ],
                errors="coerce",
            ).idxmin()

            top_row = locus_evidence.loc[
                top_index
            ]

        recurrence = variant_recurrence.loc[
            variant_recurrence[
                "lead_rsid"
            ].eq(
                lead_rsid
            )
        ]

        recurrent = recurrence.loc[
            recurrence[
                "study_count"
            ].ge(
                2
            )
        ]

        maximum_variant_study_recurrence = (
            int(
                recurrence[
                    "study_count"
                ].max()
            )
            if not recurrence.empty
            else 0
        )

        studies_with_regional_signal = int(
            group[
                "has_suggestive_signal"
            ]
            .fillna(
                False
            )
            .sum()
        )

        studies_with_genome_wide_signal = int(
            group[
                "has_genome_wide_signal"
            ]
            .fillna(
                False
            )
            .sum()
        )

        studies_with_direct_lead = int(
            group[
                "lead_present"
            ]
            .fillna(
                False
            )
            .sum()
        )

        studies_with_suggestive_direct_lead = int(
            (
                pd.to_numeric(
                    group[
                        "lead_p_value"
                    ],
                    errors="coerce",
                )
                <
                SUGGESTIVE_SIGNIFICANCE
            )
            .fillna(
                False
            )
            .sum()
        )

        # --------------------------------------------------------------
        # Descriptive evidence tier
        #
        # Not a causal ranking.
        # --------------------------------------------------------------

        if studies_with_genome_wide_signal >= 1:

            evidence_tier = (
                "REGIONAL_GENOME_WIDE"
            )

        elif studies_with_regional_signal >= 2:

            evidence_tier = (
                "RECURRENT_SUGGESTIVE"
            )

        elif studies_with_regional_signal == 1:

            evidence_tier = (
                "SINGLE_STUDY_SUGGESTIVE"
            )

        else:

            evidence_tier = (
                "NO_SUGGESTIVE_REGIONAL_SIGNAL"
            )

        # --------------------------------------------------------------
        # Direct-vs-regional interpretation
        # --------------------------------------------------------------

        if (
            studies_with_regional_signal
            > 0
            and
            studies_with_suggestive_direct_lead
            == 0
        ):

            signal_architecture = (
                "REGIONAL_SIGNAL_WITHOUT_DIRECT_LEAD_ASSOCIATION"
            )

        elif studies_with_suggestive_direct_lead > 0:

            signal_architecture = (
                "DIRECT_LEAD_ASSOCIATION_PRESENT"
            )

        else:

            signal_architecture = (
                "NO_SUGGESTIVE_DISEASE_SIGNAL"
            )

        records.append(
            {
                "lead_rsid":
                    str(
                        lead_rsid
                    ),

                "studies_with_locus":
                    int(
                        len(
                            group
                        )
                    ),

                "studies_with_direct_lead":
                    studies_with_direct_lead,

                "studies_with_suggestive_direct_lead":
                    studies_with_suggestive_direct_lead,

                "studies_with_suggestive_regional_signal":
                    studies_with_regional_signal,

                "studies_with_genome_wide_regional_signal":
                    studies_with_genome_wide_signal,

                "best_regional_p_value":
                    (
                        float(
                            minimum_p_values.min()
                        )
                        if not minimum_p_values.empty
                        else None
                    ),

                "best_direct_lead_p_value":
                    (
                        float(
                            lead_p_values.min()
                        )
                        if not lead_p_values.empty
                        else None
                    ),

                "best_signal_study":
                    (
                        str(
                            top_row[
                                "study_accession"
                            ]
                        )
                        if top_row is not None
                        else None
                    ),

                "best_signal_variant_rsid":
                    (
                        None
                        if (
                            top_row is None
                            or pd.isna(
                                top_row[
                                    "top_variant_rsid"
                                ]
                            )
                        )
                        else str(
                            top_row[
                                "top_variant_rsid"
                            ]
                        )
                    ),

                "best_signal_variant_id":
                    (
                        None
                        if (
                            top_row is None
                            or pd.isna(
                                top_row[
                                    "top_variant_id"
                                ]
                            )
                        )
                        else str(
                            top_row[
                                "top_variant_id"
                            ]
                        )
                    ),

                "best_signal_distance_to_lead":
                    (
                        None
                        if top_row is None
                        else _int_or_none(
                            top_row[
                                "top_variant_distance_to_lead"
                            ]
                        )
                    ),

                "nearest_top_signal_distance":
                    (
                        int(
                            top_distance_values.min()
                        )
                        if not top_distance_values.empty
                        else None
                    ),

                "suggestive_variants_observed":
                    int(
                        group[
                            "suggestive_significant_variants"
                        ].sum()
                    ),

                "suggestive_only_variants_observed":
                    int(
                        group[
                            "suggestive_only_variants"
                        ].sum()
                    ),

                "genome_wide_variants_observed":
                    int(
                        group[
                            "genome_wide_significant_variants"
                        ].sum()
                    ),

                "recurrent_suggestive_variant_count":
                    int(
                        len(
                            recurrent
                        )
                    ),

                "maximum_variant_study_recurrence":
                    maximum_variant_study_recurrence,

                "regional_evidence_tier":
                    evidence_tier,

                "signal_architecture":
                    signal_architecture,

                "ld_analysis_required":
                    bool(
                        studies_with_regional_signal
                        > 0
                        and
                        studies_with_suggestive_direct_lead
                        == 0
                    ),

                "colocalization_not_assessed":
                    True,
            }
        )

    synthesis = pd.DataFrame(
        records
    )

    if synthesis.empty:
        return synthesis

    # ------------------------------------------------------------------
    # Descriptive priority rank
    #
    # Rank:
    #   1. genome-wide regional evidence
    #   2. number of studies with p < 1e-5
    #   3. best regional p-value
    #
    # Does not represent causal probability.
    # ------------------------------------------------------------------

    synthesis = synthesis.sort_values(
        [
            "studies_with_genome_wide_regional_signal",
            "studies_with_suggestive_regional_signal",
            "best_regional_p_value",
        ],
        ascending=[
            False,
            False,
            True,
        ],
    ).reset_index(
        drop=True
    )

    synthesis[
        "descriptive_evidence_rank"
    ] = (
        synthesis.index
        + 1
    )

    return synthesis


# ============================================================================
# Public synthesis function
# ============================================================================


def synthesize_cross_study_signal(
    *,
    standardized: pd.DataFrame,
    disease_signal: pd.DataFrame,
) -> CrossStudySynthesisResult:
    """Run all M5.3C.3E synthesis components."""

    locus_evidence = build_locus_evidence(
        disease_signal
    )

    variant_recurrence = build_variant_recurrence(
        standardized
    )

    lead_synthesis = build_lead_synthesis(
        locus_evidence,
        variant_recurrence,
    )

    return CrossStudySynthesisResult(
        locus_evidence=locus_evidence,
        lead_synthesis=lead_synthesis,
        variant_recurrence=variant_recurrence,
    )