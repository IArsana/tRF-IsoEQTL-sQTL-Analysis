from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import numpy as np
import pandas as pd


GENOME_WIDE_SIGNIFICANCE = 5e-8

SUGGESTIVE_SIGNIFICANCE = 1e-5


# ============================================================================
# Models
# ============================================================================


@dataclass(frozen=True)
class CrossStudySynthesisResult:
    """Outputs generated by cross-study disease-signal synthesis."""

    locus_evidence: pd.DataFrame

    lead_synthesis: pd.DataFrame

    variant_recurrence: pd.DataFrame


# ============================================================================
# Scalar helpers
# ============================================================================


def _float_or_none(
    value: Any,
) -> float | None:
    """Return finite float or None."""

    if pd.isna(
        value
    ):
        return None

    value = float(
        value
    )

    if not np.isfinite(
        value
    ):
        return None

    return value


def _int_or_none(
    value: Any,
) -> int | None:
    """Return integer or None."""

    if pd.isna(
        value
    ):
        return None

    return int(
        value
    )


def _safe_neg_log10(
    p_value: Any,
) -> float | None:
    """Calculate -log10(p) safely."""

    value = _float_or_none(
        p_value
    )

    if value is None:
        return None

    if value <= 0:
        return None

    return float(
        -np.log10(
            value
        )
    )


# ============================================================================
# Per-locus evidence
# ============================================================================


def build_locus_evidence(
    disease_signal: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build one standardized evidence record per study × candidate lead.

    The source is the M5.3C.3D disease-signal summary.
    """

    required = {
        "study_accession",
        "lead_rsid",
        "variant_rows",
        "lead_present",
        "lead_p_value",
        "lead_beta",
        "lead_standard_error",
        "lead_effect_allele_frequency",
        "minimum_p_value",
        "top_variant_rsid",
        "top_variant_id",
        "top_variant_position",
        "top_variant_distance_to_lead",
        "top_variant_effect_allele",
        "top_variant_other_allele",
        "top_variant_beta",
        "top_variant_standard_error",
        "top_variant_eaf",
        "genome_wide_significant_variants",
        "suggestive_significant_variants",
        "suggestive_only_variants",
        "has_genome_wide_signal",
        "has_suggestive_signal",
    }

    missing = (
        required
        - set(
            disease_signal.columns
        )
    )

    if missing:

        raise ValueError(
            "Disease-signal summary is missing required columns: "
            f"{sorted(missing)}"
        )

    out = disease_signal.copy()

    # ------------------------------------------------------------------
    # Association strength
    # ------------------------------------------------------------------

    out[
        "regional_neg_log10_p"
    ] = out[
        "minimum_p_value"
    ].map(
        _safe_neg_log10
    )

    out[
        "lead_neg_log10_p"
    ] = out[
        "lead_p_value"
    ].map(
        _safe_neg_log10
    )

    # ------------------------------------------------------------------
    # Lead versus regional signal
    # ------------------------------------------------------------------

    out[
        "regional_signal_stronger_than_lead"
    ] = (
        out[
            "minimum_p_value"
        ].notna()
        &
        (
            out[
                "lead_p_value"
            ].isna()
            |
            (
                out[
                    "minimum_p_value"
                ]
                <
                out[
                    "lead_p_value"
                ]
            )
        )
    )

    # Ratio used descriptively only.
    #
    # Values >> 1 indicate that the regional top signal has a substantially
    # smaller p-value than the candidate lead itself.
    valid_ratio = (
        out[
            "minimum_p_value"
        ].notna()
        &
        out[
            "lead_p_value"
        ].notna()
        &
        out[
            "minimum_p_value"
        ].gt(
            0
        )
        &
        out[
            "lead_p_value"
        ].gt(
            0
        )
    )

    out[
        "lead_to_regional_p_ratio"
    ] = np.nan

    out.loc[
        valid_ratio,
        "lead_to_regional_p_ratio",
    ] = (
        out.loc[
            valid_ratio,
            "lead_p_value",
        ]
        /
        out.loc[
            valid_ratio,
            "minimum_p_value",
        ]
    )

    # ------------------------------------------------------------------
    # Distance
    # ------------------------------------------------------------------

    out[
        "top_variant_absolute_distance_to_lead"
    ] = (
        pd.to_numeric(
            out[
                "top_variant_distance_to_lead"
            ],
            errors="coerce",
        )
        .abs()
        .astype(
            "Int64"
        )
    )

    # ------------------------------------------------------------------
    # Descriptive signal class
    # ------------------------------------------------------------------

    out[
        "regional_signal_class"
    ] = "NO_SUGGESTIVE_SIGNAL"

    out.loc[
        out[
            "has_suggestive_signal"
        ].fillna(
            False
        ),
        "regional_signal_class",
    ] = "SUGGESTIVE"

    out.loc[
        out[
            "has_genome_wide_signal"
        ].fillna(
            False
        ),
        "regional_signal_class",
    ] = "GENOME_WIDE"

    # ------------------------------------------------------------------
    # Direct candidate-lead association class
    # ------------------------------------------------------------------

    out[
        "direct_lead_signal_class"
    ] = "LEAD_ABSENT"

    lead_present = (
        out[
            "lead_present"
        ].fillna(
            False
        )
    )

    out.loc[
        lead_present,
        "direct_lead_signal_class",
    ] = "LEAD_PRESENT_NON_SUGGESTIVE"

    out.loc[
        lead_present
        &
        out[
            "lead_p_value"
        ].lt(
            SUGGESTIVE_SIGNIFICANCE
        ),
        "direct_lead_signal_class",
    ] = "LEAD_SUGGESTIVE"

    out.loc[
        lead_present
        &
        out[
            "lead_p_value"
        ].lt(
            GENOME_WIDE_SIGNIFICANCE
        ),
        "direct_lead_signal_class",
    ] = "LEAD_GENOME_WIDE"

    # ------------------------------------------------------------------
    # Top signal identity relationship
    # ------------------------------------------------------------------

    out[
        "top_variant_is_candidate_lead"
    ] = (
        out[
            "top_variant_rsid"
        ]
        .astype(
            "string"
        )
        .str.lower()
        .eq(
            out[
                "lead_rsid"
            ]
            .astype(
                "string"
            )
            .str.lower()
        )
        .fillna(
            False
        )
    )

    return out


# ============================================================================
# Cross-study variant recurrence
# ============================================================================


def build_variant_recurrence(
    standardized: pd.DataFrame,
) -> pd.DataFrame:
    """
    Summarize recurrence of suggestive regional variants across studies.

    Only variants satisfying p < 1e-5 are included in this recurrence table.

    This is cross-study recurrence, NOT proof of independent replication.
    """

    required = {
        "study_accession",
        "lead_rsid",
        "variant_identity_key",
        "rsid",
        "variant_id",
        "chromosome",
        "base_pair_location",
        "distance_to_lead",
        "effect_allele",
        "other_allele",
        "beta",
        "standard_error",
        "effect_allele_frequency",
        "p_value",
        "is_genome_wide_significant",
        "is_suggestive_significant",
        "is_conflicting_variant_representation",
    }

    missing = (
        required
        - set(
            standardized.columns
        )
    )

    if missing:

        raise ValueError(
            "Standardized GWAS locus dataset is missing columns: "
            f"{sorted(missing)}"
        )

    significant = standardized.loc[
        standardized[
            "is_suggestive_significant"
        ].fillna(
            False
        )
    ].copy()

    if significant.empty:

        return pd.DataFrame(
            columns=[
                "lead_rsid",
                "variant_identity_key",
                "rsid",
                "variant_id",
                "chromosome",
                "base_pair_location",
                "distance_to_lead",
                "absolute_distance_to_lead",
                "studies_observed",
                "study_count",
                "minimum_p_value",
                "maximum_p_value",
                "genome_wide_in_any_study",
                "effect_direction_positive_studies",
                "effect_direction_negative_studies",
                "effect_direction_consistent",
                "conflicting_source_representation_present",
            ]
        )

    records: list[
        dict[str, Any]
    ] = []

    for (
        lead_rsid,
        variant_identity,
    ), group in significant.groupby(
        [
            "lead_rsid",
            "variant_identity_key",
        ],
        dropna=False,
        sort=True,
    ):

        if pd.isna(
            variant_identity
        ):
            continue

        p_values = pd.to_numeric(
            group[
                "p_value"
            ],
            errors="coerce",
        ).dropna()

        beta_values = pd.to_numeric(
            group[
                "beta"
            ],
            errors="coerce",
        ).dropna()

        positive = int(
            beta_values.gt(
                0
            ).sum()
        )

        negative = int(
            beta_values.lt(
                0
            ).sum()
        )

        nonzero_direction_count = (
            positive
            + negative
        )

        direction_consistent = (
            nonzero_direction_count
            > 0
            and
            (
                positive == 0
                or negative == 0
            )
        )

        first = group.iloc[
            0
        ]

        distance = _int_or_none(
            first[
                "distance_to_lead"
            ]
        )

        study_accessions = sorted(
            group[
                "study_accession"
            ]
            .astype(
                str
            )
            .unique()
            .tolist()
        )

        records.append(
            {
                "lead_rsid":
                    str(
                        lead_rsid
                    ),

                "variant_identity_key":
                    str(
                        variant_identity
                    ),

                "rsid":
                    (
                        None
                        if pd.isna(
                            first[
                                "rsid"
                            ]
                        )
                        else str(
                            first[
                                "rsid"
                            ]
                        )
                    ),

                "variant_id":
                    (
                        None
                        if pd.isna(
                            first[
                                "variant_id"
                            ]
                        )
                        else str(
                            first[
                                "variant_id"
                            ]
                        )
                    ),

                "chromosome":
                    (
                        None
                        if pd.isna(
                            first[
                                "chromosome"
                            ]
                        )
                        else str(
                            first[
                                "chromosome"
                            ]
                        )
                    ),

                "base_pair_location":
                    _int_or_none(
                        first[
                            "base_pair_location"
                        ]
                    ),

                "distance_to_lead":
                    distance,

                "absolute_distance_to_lead":
                    (
                        abs(
                            distance
                        )
                        if distance is not None
                        else None
                    ),

                "studies_observed":
                    "|".join(
                        study_accessions
                    ),

                "study_count":
                    int(
                        len(
                            study_accessions
                        )
                    ),

                "minimum_p_value":
                    (
                        float(
                            p_values.min()
                        )
                        if not p_values.empty
                        else None
                    ),

                "maximum_p_value":
                    (
                        float(
                            p_values.max()
                        )
                        if not p_values.empty
                        else None
                    ),

                "genome_wide_in_any_study":
                    bool(
                        group[
                            "is_genome_wide_significant"
                        ]
                        .fillna(
                            False
                        )
                        .any()
                    ),

                "effect_direction_positive_studies":
                    positive,

                "effect_direction_negative_studies":
                    negative,

                "effect_direction_consistent":
                    bool(
                        direction_consistent
                    ),

                "conflicting_source_representation_present":
                    bool(
                        group[
                            "is_conflicting_variant_representation"
                        ]
                        .fillna(
                            False
                        )
                        .any()
                    ),
            }
        )

    recurrence = pd.DataFrame(
        records
    )

    if recurrence.empty:
        return recurrence

    return recurrence.sort_values(
        [
            "lead_rsid",
            "study_count",
            "minimum_p_value",
        ],
        ascending=[
            True,
            False,
            True,
        ],
    ).reset_index(
        drop=True
    )


