# ===========================================================================
# Multiple anomalies
# ===========================================================================


def test_multiple_invalid_snp_ids_generate_multiple_anomalies() -> None:
    """
    Multiple invalid SNP identifiers must be reported independently.
    """

    validator = create_validator()

    result = validator.validate_snp_ids(
        [
            "INVALID1",
            "rs123",
            "INVALID2",
        ],
        "SNP ID",
    )

    assert len(result) == 2

    assert all(
        "TRFQTL-SNP-001" in message
        for message in result
    )


def test_anomaly_messages_include_invalid_value() -> None:
    """
    Anomaly messages should retain the offending value for traceability.
    """

    validator = create_validator()

    result = validator.validate_snp_ids(
        ["INVALID"],
        "SNP ID",
    )

    assert len(result) == 1
    assert "INVALID" in result[0]


# ===========================================================================
# Known dataset anomaly
# ===========================================================================


def test_s10_invalid_snp_id_is_classified_consistently() -> None:
    """
    The known S10 anomaly where SNP ID '6' appears instead of an rsID
    must use the same SNP anomaly classification as other invalid SNP IDs.

    This test documents the observed source-data anomaly without
    modifying or silently correcting the original dataset.
    """

    validator = create_validator()

    result = validator.validate_snp_ids(
        ["6"],
        "SNP ID",
    )

    assert len(result) == 1
    assert "TRFQTL-SNP-001" in result[0]
    assert "6" in result[0]