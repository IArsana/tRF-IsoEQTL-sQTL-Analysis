from __future__ import annotations

from pcatrfqtl.validation.validators.trfqtl import TRFQTLValidator

def create_validator() -> TRFQTLValidator:
    """
    Create a TRFQTL validator for unit testing.
    """
    return TRFQTLValidator()


# ===========================================================================
# SNP ID anomalies
# ===========================================================================


def test_invalid_snp_id_has_anomaly_id() -> None:
    """
    Invalid SNP identifiers must generate a classified anomaly.
    """

    validator = create_validator()

    result = validator.validate_snp_ids(
        [
            "rs123",
            "INVALID",
        ],
        "SNP ID",
    )

    assert len(result) == 1
    assert "TRFQTL-SNP-001" in result[0]


def test_invalid_snp_id_anomaly_is_stable() -> None:
    """
    The anomaly identifier must remain stable across repeated validation.
    """

    validator = create_validator()

    first = validator.validate_snp_ids(
        ["INVALID"],
        "SNP ID",
    )

    second = validator.validate_snp_ids(
        ["INVALID"],
        "SNP ID",
    )

    assert first == second
    assert "TRFQTL-SNP-001" in first[0]


